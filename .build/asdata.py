def _b64(path):
    with open(path, "rb") as f:
        return base64.b64encode(f.read()).decode()


def clip(nn):
    return "data:video/mp4;base64," + _b64(f".build/as/clips/{nn}.mp4")


def poster(nn):
    return "data:image/jpeg;base64," + _b64(f".build/as/poster/{nn}.jpg")


